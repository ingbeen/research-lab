"""research-lab 공통 상수

두 개 이상의 계층에서 함께 쓰는 값을 단일 관리한다 — 경로와 파일명이다.
한 계층에서만 쓰는 값은 그 계층이 소유한다. 판단 기준은 `src/research_lab/CLAUDE.md` 를 따른다.
"""

from pathlib import Path
from typing import Final
from zoneinfo import ZoneInfo

# ============================================================
# 경로 상수
# ============================================================

# 저장소 루트 (이 파일 기준 2단계 상위: src/research_lab -> src -> 루트).
# 실행 디렉터리(CWD)를 기준으로 삼지 않는다. 컨테이너 안에서는 `/work`, 호스트에서는
# 사람이 연 폴더에서 실행되므로, CWD 를 믿으면 같은 회차의 산출물이 두 곳으로 흩어진다
BASE_DIR: Final = Path(__file__).resolve().parents[2]

# 후보 목록. 「탐색」이 append 하고 「수집」이 꺼내 쓴다.
# 사람도 손으로 고칠 수 있으며, 이 저장소가 만드는 누적 상태 중 하나다 —
# 하루를 걸러도 그 회차가 없었을 뿐 영구 손상이 아니기 때문이다
LEDGER_DIR: Final = BASE_DIR / "ledger"
LEDGER_PATH: Final = LEDGER_DIR / "원장.md"

# 완성된 근거 문서. 저장소 «밖»으로 나가는 유일한 산출물이라 다른 문서를 가리키지 않는다
DOSSIER_DIR: Final = BASE_DIR / "dossier"

# 그 회차의 원자료 — 검색어·URL·결정 로그·실패 원문.
# [결정 2026-09-12] git 에 포함한다. 기계를 옮겨도 과거를 훑을 수 있어야 게이트 기준을
# 바꿨을 때 「지금 기준이면 판정이 달라졌을 후보」를 찾아낼 수 있다. 근거는 `docs/DESIGN.md`
RUNS_DIR: Final = BASE_DIR / "runs"

DOCS_DIR: Final = BASE_DIR / "docs"

# 「무엇을 받을 수 있나」의 요약. 회차의 마지막 단계가 먹는 «입력»이다.
#
# [중요] 러너가 본문을 읽어 프롬프트에 실어 보낸다. 경로만 가리키면 읽혔는지 확인할 길이
# 없고, 안 읽어도 **에러 없이 「이미 있음」만 조용히 안 나온다** — 그것이 이 단계의 완료
# 조건이라, 확인할 수 없는 자리에 두면 안 된다.
#
# [주의] 이 파일이 없어도 회차는 돈다. 카탈로그는 검사기가 아니라 입력이고, 문서 한 장이
# 파이프라인을 멈추면 무인 실행에는 고칠 사람이 없다
DATA_CATALOG_PATH: Final = DOCS_DIR / "DATA_CATALOG.md"

# 러너가 «쓰는» 곳 전부. 자격증명 스캔의 범위가 여기서 나온다.
#
# [중요] 저장소 전체를 스캔하지 않는다. 계약 테스트와 계획서에는 탐지 패턴이 «리터럴»로
# 들어 있어, 범위를 넓히면 검사기가 자기 자신과 자기 계획서에 걸린다.
#
# [중요] 그렇다고 이 목록을 그대로 스캔하지도 않는다. `RUNS_DIR` 는 지난 회차들이 모두 쌓이는
# 곳이라, 과거 어느 회차에 한 번 걸린 파일이 **이후 모든 회차를 영구히 실패시킨다.**
# 실제 검사 범위는 `gate/secrets.py` 의 `scan_roots(run_dir)` 가 만들며
# `RUNS_DIR` 자리에 **그 회차의 실행 폴더 하나만** 넣는다
WRITABLE_ROOTS: Final = (RUNS_DIR, DOSSIER_DIR, LEDGER_DIR)

# ============================================================
# 파일명
# ============================================================

# [중요] 파일명은 러너와 에이전트가 공유하는 계약이다. 한 곳만 달라져도 예외는
# 「파일 없음」으로만 뜨며, 무엇이 어긋났는지가 드러나지 않는다. 그래서 한 곳에서만 정한다

# 어디까지 했는지. 임시 파일에 쓰고 성공했을 때만 이 이름으로 rename 한다
STATE_FILENAME: Final = "state.json"

# 동시 실행 잠금. rename 은 원자적이지만 «번갈아 쓰는 것»은 막지 못한다 —
# 두 프로세스가 같은 상태 파일을 갈아쓰면 한쪽 갱신이 조용히 사라진다
LOCK_FILENAME: Final = "lock"

# 과정의 기록. 줄글이 아니라 JSONL 인 이유는 「나중에 기계가 훑을 것」이기 때문이다 —
# 게이트 기준을 바꿨을 때 「지금 기준이면 판정이 달라졌을 후보」를 찾아낼 수 있어야 한다
DECISION_LOG_FILENAME: Final = "decisions.jsonl"

# 각 단계의 산출물.
# [주의] 이 이름들은 사람이 읽는 산출물이라 한글이다. 반면 파이썬 식별자와 내부 키는
# 영문으로 둔다 — 저장소의 기존 관용과 같다
PRO_EVIDENCE_FILENAME: Final = "찬성근거.json"
SEARCH_QUERIES_FILENAME: Final = "검색어.json"
EXPLORE_RESULT_FILENAME: Final = "탐색결과.json"

# 반증은 «별도 세션»이 낸다. 찬성 근거와 다른 파일에 두는 이유는 둘을 섞으면
# 「이 출처가 어느 쪽에서 나왔나」가 흐려지고, 계보 단계가 그것을 구별해 읽어야 하기 때문이다
REBUTTAL_FILENAME: Final = "반증.json"

# 반증 세션이 던진 검색어. 수집의 것과 «다른 파일»인 이유는 둘이 서로 다른 세션의 기록이라,
# 한 파일에 합치면 「반대편으로 갈아 끼웠나」를 되짚을 수 없기 때문이다
REBUTTAL_QUERIES_FILENAME: Final = "반증검색어.json"

# 「세 곳에서 확인」이 아니라 「한 원본 · 복제 두 곳」을 담는 표
LINEAGE_FILENAME: Final = "계보.json"

# dossier 의 4번 칸(데이터 실현가능성)과 5번 칸(집행 현실성).
#
# 한 파일에 둘을 담는 이유는 **같은 호출이 둘을 함께 내기** 때문이다. 나누면 한쪽만 쓰인
# 상태가 생기고, 그것이 「칸이 비었다」와 구별되지 않는다
FEASIBILITY_FILENAME: Final = "실현가능성.json"

# ============================================================
# 시간대
# ============================================================

# 실행 폴더 이름과 로그 타임스탬프의 기준 시간대.
# 컨테이너 기본 시간대는 UTC 라, 기준을 명시하지 않으면 같은 회차가 날짜 두 개로 갈린다
KST: Final = ZoneInfo("Asia/Seoul")

# 실행 폴더 이름. 하루에 두 번 돌 수 있으므로 날짜만으로는 유일해지지 않는다
RUN_DIR_TIME_FORMAT: Final = "%Y%m%d_%H%M"
