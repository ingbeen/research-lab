"""회차의 단계 정의와 「어디부터 이어받나」 판정.

회차는 한 세션을 길게 돌리는 구조가 아니다. 단계마다 짧게 부르고 산출물을 파일로 인계하므로
어디서 끊겨도 그 단계부터 다시 시작한다. `--resume` 은 보험이지 뼈대가 아니다.
"""

from collections.abc import Sequence
from typing import Final

# 회차가 도는 순서.
#
# [중요] 이 이름은 상태 파일에 기록돼 다음 회차가 읽는 «식별자»다. 표시용 문구가 아니므로
# 영문으로 두고, 바꿀 때는 예전 상태 파일을 어떻게 다룰지 함께 정해야 한다 —
# 그러지 않으면 끝난 단계를 처음부터 다시 돌면서 예산만 두 배로 쓴다.
#
# 「탐색」이 먼저인 이유는 그것이 「수집」의 입력을 만들기 때문이다.
# 원장이 비어 있으면 수집이 팔 후보가 없다.
#
# 「반증」이 「수집」 뒤인 것은 순서가 중요해서가 아니라 **수집이 그 회차의 후보를 정하기**
# 때문이다. 반증은 그 후보의 한 줄 주장만 받으며 수집이 무엇을 찾았는지 모른다.
# 「계보」가 그 뒤인 것은 그것이 **양쪽 출처를 모두 받아야** 「누가 원본인가」를 묻기 때문이다.
#
# 「실현가능성」이 출처 쪽 칸들 뒤인 것은 dossier 를 채우는 순서가 `6→7→8→9→4→5→3` 이라
# **4·5번 칸이 그 뒤**에 오기 때문이다.
#
# 「메커니즘」(3·9번 칸)이 그 뒤인 것은 **앞이 모은 출처를 읽어야** 「왜 우위가 있나」와
# 「그 우위가 아직 살아 있나」를 물을 수 있기 때문이다. 문서에서의 칸 번호 순서와 다른
# 것이 정상이다 — 단계 순서를 정하는 것은 **입력이 준비되는 순서**이지 칸 번호가 아니다.
#
# 「측정 설계」(10번 칸)가 그 뒤인 것은 수집의 파라미터 축과 실현가능성의 시장·상품을
# 받아야 격자를 그 후보에 맞게 짤 수 있기 때문이다.
#
# [중요] 「판정」(2번 칸)이 **맨 마지막**이다. 측정 설계와 한 호출에 담으면 에이전트가
# 판정을 먼저 정하고 측정 설계를 거기 맞출 수 있는데, 이 저장소는 프롬프트 지시가
# 형식적으로만 지켜진 것을 여러 번 확인했다. **순서를 지시가 아니라 단계 경계로 보장한다.**
# 그리고 「판 것」 표시도 이 마지막 단계가 한다
# 후보를 «만드는» 단계와 «고르는» 단계.
#
# [중요] 이름을 여기서 한 번 정하고 쓰는 쪽이 그것을 가리킨다. 부르는 쪽이 위치(`STEPS[0]`)로
# 집으면 **앞에 단계를 하나 끼우는 순간 다른 단계를 가리키게 되고**, 그 어긋남은 예외가 아니라
# 「건너뛰기 판정이 조용히 뒤바뀌는」 모양으로 나타난다 — 아래 `STEPS_WITHOUT_CANDIDATE` 가
# 위치로 자르지 않는 것과 같은 이유이며, 그 경고가 이 둘에도 그대로 적용된다
EXPLORE: Final = "explore"
COLLECT: Final = "collect"

STEPS: Final = (
    EXPLORE,
    COLLECT,
    "rebut",
    "lineage",
    "feasibility",
    "mechanism",
    "measurement",
    "verdict",
)

# 그 회차의 «후보»가 정해져 있어야 돌 수 있는 단계들.
#
# [중요] 후보가 없는데 이 단계를 돌리면 «끝나지 않는 실패»가 된다 — 예외가 나고 상한까지
# 재시도한 뒤 「다음 회차가 이어받습니다」로 보고되며, 다음 회차도 같은 자리에서 같은 일을
# 반복한다. 그래서 러너가 건너뛰고, 진입점이 그런 예전 상태 파일을 이어받지 않는다.
#
# 「탐색」과 「수집」을 뺀 나머지 전부다 — 탐색은 후보를 만드는 자리이고 수집이 그중 하나를
# 고르는 자리이므로, 그 둘만 후보 없이 시작할 수 있다.
#
# [중요] 위치(`STEPS[2:]`)로 자르지 않는다. 앞쪽에 단계를 하나 끼우면 **수집이 이 목록에
# 들어가고**, 그러면 러너가 「후보가 없다」며 수집을 건너뛴다 — 후보를 «만드는» 단계가
# 후보가 없어서 안 도는 상태가 되어 파이프라인이 조용히 영영 멈춘다.
# 이름으로 가르면 단계를 어디에 끼워도 그 뜻이 유지된다
STEPS_WITHOUT_CANDIDATE: Final = (EXPLORE, COLLECT)
CANDIDATE_STEPS: Final = tuple(name for name in STEPS if name not in STEPS_WITHOUT_CANDIDATE)


class UnknownStepError(ValueError):
    """상태 파일에 정의되지 않은 단계 이름이 들어 있을 때."""


class StepNotImplementedError(RuntimeError):
    """정의된 단계인데 실행부가 없을 때 — 내부 불변조건 위반.

    [중요] 이것은 «실패»가 아니라 «고장»이라 재시도 대상이 아니다. 「그 외」로 묻히면
    상한까지 헛돌고 나서 「다음 회차가 이어받습니다」라는 종료 코드로 보고되어,
    **아무 일도 안 하는 상태를 정상으로 알린다.** 그래서 러너가 이 예외만은 그대로 터뜨린다.
    """


class StepFailed(RuntimeError):
    """단계가 실패했을 때. **에이전트의 출력 원문을 그대로 들고 다닌다.**

    분류는 `failures.classify` 가 하고 이 예외는 나르기만 한다. 여기서 미리 분류하면
    분류표를 고칠 때 예외를 올리는 쪽까지 따라 고쳐야 하고, 무엇보다 **원문이 요약되면
    처음 한도에 부딪히는 날 그 답을 못 얻는다.**
    """

    def __init__(self, raw: str) -> None:
        super().__init__(raw)
        self.raw = raw


class StepQualityFailed(StepFailed):
    """산출물이 규율을 못 지켰을 때 — 게이트가 막은 것이다.

    [중요] **재시도 대상이 아니다.** 네트워크 끊김처럼 「기다리면 풀리는」 것이 아니라
    그 호출의 결과 자체가 기준에 못 미친 것이라, 같은 회차에 세 번 더 부르면
    **full 예산을 세 번 더 쓰고도 같은 자리에 설 공산이 크다.**
    그 회차는 미완성으로 끝내고 다음 회차가 다시 잡는다.
    """


def next_step(completed: Sequence[str]) -> str | None:
    """다음에 실행할 단계를 고른다.

    Args:
        completed: 이미 끝난 단계 이름들. 실패·재시도로 **순서가 뒤섞여 있을 수 있다**

    Returns:
        정의된 순서 기준으로 아직 안 한 첫 단계. 다 끝났으면 None —
        마지막 단계를 돌려주면 완성된 산출물 위에 다시 쓴다

    Raises:
        UnknownStepError: 정의에 없는 이름이 들어 있을 때. 조용히 무시하면
            **끝난 단계를 처음부터 다시 돈다**
    """
    unknown = [name for name in completed if name not in STEPS]
    if unknown:
        raise UnknownStepError(
            f"정의에 없는 단계가 상태에 들어 있습니다: {unknown}. " f"단계 이름을 바꿨다면 예전 상태 파일을 어떻게 다룰지 먼저 정하세요. " f"정의된 단계: {list(STEPS)}"
        )

    done = set(completed)
    # 기록된 순서가 아니라 «정의된 순서»로 판정한다.
    # 목록의 마지막 원소를 보고 다음을 정하면 엉뚱한 단계로 건너뛴다
    for name in STEPS:
        if name not in done:
            return name
    return None
