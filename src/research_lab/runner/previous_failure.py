"""앞선 시도가 품질 게이트에 막혔으면 그 사유를 «다음 시도의 지시문»에 싣는다.

품질 실패는 회차 안에서 재시도되지 않는다 — 기다려서 풀리는 고장이 아니라 결과의 질이
문제라서다. 그런데 그 사유가 다음 시도에 안 실리면 **에이전트는 무엇이 막혔는지 모른 채
같은 표현 · 같은 주소를 다시 내고**, 같은 자리에서 세 번 막히면 멀쩡한 후보가 원장에서
걷힌다. 자립성 사전이 외부 카탈로그를 말한 정상 문장을 무는 오탐이 그런 «고칠 수 있는데
못 고치는» 실패의 예다 — 사전을 좁히는 대신 고칠 기회를 준다.

[중요] **후보가 박힌 단계만** 이것을 지난다(반증 이후). 그 단계들은 같은 폴더에서 같은 후보를
다시 도므로 직전 사유가 그대로 그 후보의 것이다. 탐색 · 수집은 빠진다 — 수집은 자기
재질문 장치(죽은 출처를 짚어 다시 묻고 · 미룬다)가 있고 후보가 회차마다 바뀔 수 있어
「같은 후보의 직전 사유」가 성립하지 않는다. 탐색의 품질 실패(검색어 하한)는 재고가 생기면
다시 돌지 않는다.

[중요] **반증 세션의 분리를 깨지 않는다.** 반증에 실리는 것은 반증 «자신의» 앞선 사유뿐이라
찬성 근거가 새지 않는다 — 읽는 줄을 단계 이름으로 가르는 것이 그 보장이다.
"""

from pathlib import Path
from typing import Final

from research_lab.runner import decision_log

# 지시문 끝에 붙이는 절.
#
# [중요] 「무엇을 어떻게 고치라」를 여기서 정하지 «않는다». 사유마다 고칠 방향이 반대일 수 있다 —
# 자립성은 짚인 표현을 «빼라»지만 계보의 누락은 짚인 주소를 «넣으라»다. 여기서 「짚인 것을 다시
# 내지 말라」로 뭉뚱그리면 누락 사유에서 **정반대로 읽혀** 같은 자리에서 또 막힌다. 방향은
# 사유 문장이 이미 말하므로, 이 절은 「그 사유대로 고치라 · 같은 답은 또 막힌다」만 준다
SUFFIX: Final = """

## 앞선 시도가 막혔습니다 — 그 자리를 고쳐 냅니다

이 단계의 앞선 시도가 아래 사유로 막혔습니다. 사유를 읽고 **사유가 말하는 대로** 그 자리를 고치세요.
앞선 답과 같은 답을 내면 같은 자리에서 또 막히고, 같은 자리에서 세 번 막히면 이 후보는 더 파지 않게
됩니다. 나머지 규율은 위와 같습니다.

> {reason}
"""


def with_previous_failure(prompt: str, run_dir: Path, step: str) -> str:
    """그 단계의 직전 품질 실패가 있으면 그 사유를 지시문 끝에 붙인다.

    Args:
        prompt: 그 단계의 원래 지시문
        run_dir: 그 회차의 실행 폴더
        step: 그 단계의 이름. **이 이름의 줄만** 읽는다

    Returns:
        사유가 붙은 지시문. 품질 실패가 없으면 원래 지시문 그대로 — 처음 도는 단계에
        「앞선 시도가 막혔다」가 붙으면 에이전트는 없는 잘못을 고치려 든다
    """
    reason = decision_log.last_quality_failure(run_dir, step)
    if reason is None:
        return prompt
    # 여러 줄 사유가 인용 밖으로 새지 않게 한 줄로 편다
    return prompt + SUFFIX.format(reason=" ".join(reason.split()))
