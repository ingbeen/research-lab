"""근거 문서가 «함께 가지 않는 문서»를 가리키는지 본다.

이 저장소의 1순위 제약은 **「근거 문서는 다른 문서를 한 장도 열지 않고 판단할 수 있어야
한다」**이다. 저장소 밖으로 나가는 순간 포인터는 전부 죽고, 그때 잃는 것은 링크가 아니라
**판단 가능성**이다 — 「그 기준에 걸린다」로 적힌 판정은 그 기준이 없는 자리에서
왜 그런 판정인지 물을 방법이 없다.

[중요] 그 제약을 지키는 장치가 러너의 «고정 문구»에만 걸려 있었다. 에이전트가 쓴 산문은
아무도 보지 않았고, [실측 2026-09-15] 실제로 나간 문서의 **2번 칸(판정)**이
「이 스킬이 예로 든 …과 사실상 같은 모양이다」로 판정 근거를 댔다.

[중요] **사전 매칭만 한다. 「자립적으로 잘 썼나」를 재지 않는다.** 재려고 들면 게이트가
또 하나의 판단자가 된다 — 이 저장소가 게이트마다 지켜 온 선이다. 보는 것은
「가리키는 말이 적혔나」뿐이고, 그 말이 실제로 무엇을 가리키는지는 판정하지 않는다.

[중요] **오탐의 대가가 누락의 대가보다 훨씬 작다.** 걸리면 그 회차가 미완성이 되고
다음 회차가 다시 쓴다. 놓치면 **판단 불가능한 문서가 저장소 밖으로 나가고 되돌릴 수 없다.**
그래서 사전을 넉넉히 두되, 늘릴 때는 **회차에서 실제로 나온 표현**으로 늘린다.
"""

from typing import Any, Final

# 문서와 «함께 가지 않는» 것을 가리키는 말.
#
# [중요] 씨앗은 실측에서 왔다 — 「이 스킬」은 실제로 나간 문서가 판정 근거로 쓴 말이다.
# 겪지 않은 표현을 미리 채우지 않는다.
#
# [중요] **가리키는 대상이 «문서 밖»임이 말 자체로 확정되는 것만 담는다.** 이 저장소에는
# 「스킬」도 「저장소」도 근거 문서와 함께 가지 않으므로, 그 말이 있으면 대상이 무엇이든
# 밖이다. 반대로 대상이 문서 «안»일 수 있는 말은 담지 않는다.
#
# [주의] 「이 문서」를 넣지 «않는» 이유가 그것이고, [탈락 2026-09-15] 같은 이유로 셋을 뺐다.
#
# | 뺀 것 | 무는 멀쩡한 문장 |
# | --- | --- |
# | `§` | 「미국 세법 §355 상 적격 분할이면 비과세다」 — 분할 상장은 이 저장소의 «실제 후보 주제»다 |
# | `원칙 ` | 「회계 원칙 (GAAP) 상 인식 시점이 다르다」 |
# | `앞서 말한` · `위에서 본` | 같은 칸 «안»의 앞 문장을 가리키는 것은 자립을 깨지 않는다 |
#
# [중요] **오탐의 대가를 「다음 회차가 다시 쓴다」로 계산했던 것이 틀렸다.** 품질 실패는
# 회차 «안»에서 재시도되지 않고 사유가 지시문으로 되먹여지지도 않으므로, 계통 오탐은
# **매 회차 같은 자리에서 반복되고 세 번이면 그 후보가 원장에서 걷힌다.**
# 세는 목록(비용어)과 달리 이쪽은 **막는 목록**이라 오탐의 대가가 0 이 아니다.
POINTER_TERMS: Final = (
    "이 스킬",
    "그 스킬",
    "해당 스킬",
    "이 저장소",
    "그 저장소",
    "해당 저장소",
    "위 문서",
    # [실측 2026-09-26] 아래 「카탈로그」 꼴들은 나간 근거 문서들이 저장소 안의 데이터 카탈로그를
    # 가리킨 말에서 왔다 — 「(카탈로그에 실측 없음)」 · 「카탈로그는 …만 확인했지」 ·
    # 「이는 카탈로그에 없어」. 카탈로그는 근거 문서와 함께 가지 않는다.
    #
    # [중요] **이름만으로는 막지 않고 조사가 붙은 꼴만 막는다.** 실현가능성 지시문은 그 목록을
    # 「데이터 카탈로그」라는 이름으로 싣는다. 이름 자체를 막으면 지시문이 다른 이름으로 불러야
    # 하고, 에이전트는 **그 새 이름으로** 가리키기 시작해 사전 밖으로 샌다 — 에이전트는
    # 프롬프트에서 받은 말을 제 답에 되돌려 쓴다(지시문이 「이 저장소」로 시작하자 답에 그 말이
    # 나온 2026-09-16 실측). **같은 이유로 지칭어를 바꿔 피하지도 않는다.** 대신 지시문 ·
    # 카탈로그 · 리서치 스킬이 되돌려 쓸 말 자체를 «자립 문장»으로 준다 —
    # 「이 파이프라인이 실측한 기록 없음」.
    #
    # 조사는 실제로 나온 꼴(에 · 는)에 **에이전트가 읽는 글(지시문 · 카탈로그 · 리서치
    # 스킬)에 적혀 있던 꼴**(가 · 를 · 의)을 더했다. 「겪은 표현으로 늘린다」의 겪은 자리를
    # 산출물에서 입력까지 넓힌 것이다 — 입력에 있던 꼴은 에이전트가 되돌려 쓸 수 있는 꼴이다
    "카탈로그에",
    "카탈로그는",
    "카탈로그가",
    "카탈로그를",
    "카탈로그의",
)


def pointers_in(text: Any) -> tuple[str, ...]:
    """그 본문에 든 «가리키는 말»을 센다.

    Args:
        text: 조립된 칸 본문. 모양이 어긋나 있어도 된다

    Returns:
        걸린 표현. **정의된 순서**로 돌려준다 — 회차마다 순서가 달라지면 로그를 대조할 수 없다

    [중요] 문자열이 아닌 값은 «본문이 없는 것»으로 본다. `str()` 로 감싸면 JSON 의 `null` 이
    `"None"` 이라는 내용 있는 문자열이 되고, 그 가짜 본문이 검사 대상에 들어간다.
    """
    if not isinstance(text, str):
        return ()
    return tuple(term for term in POINTER_TERMS if term in text)


def shortfall_reason(sections: Any) -> str | None:
    """가리키는 말이 있으면 그 사유를, 없으면 None 을 돌려준다.

    Args:
        sections: `{칸 이름: 조립된 본문}`. 모양이 어긋나 있어도 된다

    Returns:
        걸렸을 때의 사유, 없으면 None

    [중요] 「거부됨」만 돌려주지 않는다. **어느 칸의 어느 표현이** 걸렸는지와
    **대신 무엇을 적어야 하는지**가 함께 돌아가야 다음 회차가 같은 문장을 다시 쓰지 않는다.

    [중요] 어떤 입력에도 예외를 올리지 않는다 — 검사기가 죽으면 고칠 수 있었던 것까지
    그 회차를 끝낸다.
    """
    if not isinstance(sections, dict):
        return None

    # [중요] 첫 자리에서 멈추지 «않는다». 품질 실패는 회차 안에서 재시도되지 않으므로,
    # 한 번에 하나씩 알리면 걸린 자리 수만큼 회차가 들고 **세 번이면 후보가 걷힌다.**
    # 전부 모아 돌려주는 비용은 0 이다
    offenders = [(label, found) for label, text in sections.items() if (found := pointers_in(text))]
    if not offenders:
        return None

    listed = " / ".join(f"{label}: " + " · ".join(f"「{term.strip()}」" for term in found) for label, found in offenders)
    return (
        f"이 문서와 «함께 가지 않는» 것을 가리키는 말이 있습니다 — {listed}. "
        f"근거 문서는 저장소 밖으로 나가므로 그 자리에서 가리키는 대상이 사라지고, "
        f"링크가 깨지는 것이 아니라 «판단이 불가능»해집니다. "
        f"가리키는 대신 «기준 자체»를 그 자리에 적으세요 — "
        f"「그 기준에 걸린다」가 아니라 「칸당 10건 미만이면 우연과 구별되지 않는다」처럼 씁니다."
    )
